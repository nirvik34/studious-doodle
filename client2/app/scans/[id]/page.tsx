"use client";

import { useEffect, useState } from "react";
import { useParams, useRouter } from "next/navigation";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { RiskBadge } from "@/components/shared/RiskBadge";
import { ArrowLeft, Download, Eye, Calendar, Activity } from "lucide-react";
import Link from "next/link";
import { motion } from "framer-motion";

export default function ScanDetailPage() {
  const params = useParams();
  const router = useRouter();
  const [scan, setScan] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const fetchScan = async () => {
      try {
        const id = Array.isArray(params?.id) ? params.id[0] : params?.id;
        if (!id) {
          setError('Invalid scan ID');
          setLoading(false);
          return;
        }
        
        const response = await fetch(`/api/scans/${id}`);
        if (!response.ok) {
          throw new Error('Scan not found');
        }
        const data = await response.json();
        setScan(data.scan);
      } catch (error) {
        console.error('Error fetching scan:', error);
        setError(error instanceof Error ? error.message : 'Failed to load scan');
      } finally {
        setLoading(false);
      }
    };

    fetchScan();
  }, [params]);

  const downloadReport = () => {
    if (!scan) return;

    const reportContent = `
FACIAL ASYMMETRY ANALYSIS REPORT
================================

Date: ${new Date(scan.timestamp || scan.createdAt).toLocaleString()}
Report ID: ${scan._id}

OVERALL ASSESSMENT
------------------
Risk Score: ${scan.riskScore}%
Risk Level: ${scan.riskLevel}
AI Confidence: ${scan.confidence}%
Raw Asymmetry Score: ${scan.rawAsymmetryScore?.toFixed(4) || 'N/A'}

FACIAL METRICS BREAKDOWN
-------------------------
${scan.facialMetrics ? `
Overall: ${scan.facialMetrics.overall}%
Chin: ${scan.facialMetrics.chin}%
Left Eye: ${scan.facialMetrics.leftEye}%
Right Eye: ${scan.facialMetrics.rightEye}%
Mouth: ${scan.facialMetrics.mouth}%
Nose: ${scan.facialMetrics.nose}%
Left Cheek: ${scan.facialMetrics.leftCheek}%
Right Cheek: ${scan.facialMetrics.rightCheek}%
Forehead: ${scan.facialMetrics.forehead}%
` : 'No detailed metrics available'}

DETECTED FACTORS
----------------
${scan.factors?.map((f: string) => `- ${f}`).join('\n') || 'None'}

DETECTED FEATURES
-----------------
${scan.detectedFeatures?.map((f: string) => `- ${f}`).join('\n') || 'None'}

RECOMMENDATIONS
---------------
${scan.recommendations?.map((r: string, i: number) => `${i + 1}. ${r}`).join('\n') || 'None'}

RISK LEVEL GUIDE
----------------
Low Risk (0-30%): Minimal facial asymmetry detected
Medium Risk (31-70%): Noticeable asymmetry, consider consulting a healthcare professional
High Risk (71-100%): Significant asymmetry detected, seek immediate medical attention

DISCLAIMER
----------
This report is generated by an AI-powered facial asymmetry detection system.
Results should be discussed with qualified healthcare professionals.
This is not a medical diagnosis and should not be used as the sole basis for medical decisions.

Generated by Facial Asymmetry Detection System
Report Date: ${new Date().toLocaleString()}
    `;

    const blob = new Blob([reportContent], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `facial-analysis-report-${scan._id}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  if (loading) {
    return (
      <div className="container py-16 text-center">
        <div className="animate-spin h-8 w-8 border-4 border-primary border-t-transparent rounded-full mx-auto" />
        <p className="mt-4 text-muted-foreground">Loading scan details...</p>
      </div>
    );
  }

  if (error || !scan) {
    return (
      <div className="container py-16 text-center space-y-4">
        <div className="text-6xl">❌</div>
        <h1 className="text-2xl font-bold">{error || 'Scan not found'}</h1>
        <p className="text-muted-foreground">The scan you're looking for doesn't exist or has been deleted.</p>
        <Link href="/dashboard">
          <Button variant="outline" className="gap-2">
            <ArrowLeft className="h-4 w-4" />
            Back to Dashboard
          </Button>
        </Link>
      </div>
    );
  }

  const getScoreColor = (score: number) => {
    if (score < 30) return "text-green-600";
    if (score < 70) return "text-yellow-600";
    return "text-red-600";
  };

  const getProgressColor = (score: number) => {
    if (score < 30) return "bg-green-500";
    if (score < 70) return "bg-yellow-500";
    return "bg-red-500";
  };

  return (
    <div className="container py-8 space-y-6 max-w-6xl">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-4">
          <Link href="/dashboard">
            <Button variant="outline" size="sm">
              <ArrowLeft className="h-4 w-4 mr-2" />
              Back
            </Button>
          </Link>
          <div>
            <h1 className="text-3xl font-bold">Scan Report Details</h1>
            <p className="text-muted-foreground">
              Detailed facial asymmetry analysis results
            </p>
          </div>
        </div>
        <Button onClick={downloadReport} className="gap-2">
          <Download className="h-4 w-4" />
          Download Report
        </Button>
      </div>

      {/* Summary Cards */}
      <div className="grid gap-4 md:grid-cols-4">
        <Card>
          <CardHeader className="pb-2">
            <CardTitle className="text-sm font-medium text-muted-foreground">
              Risk Score
            </CardTitle>
          </CardHeader>
          <CardContent>
            <div className={`text-3xl font-bold ${getScoreColor(scan.riskScore)}`}>
              {scan.riskScore}%
            </div>
          </CardContent>
        </Card>

        <Card>
          <CardHeader className="pb-2">
            <CardTitle className="text-sm font-medium text-muted-foreground">
              Risk Level
            </CardTitle>
          </CardHeader>
          <CardContent>
            <RiskBadge level={scan.riskLevel} className="text-lg" />
          </CardContent>
        </Card>

        <Card>
          <CardHeader className="pb-2">
            <CardTitle className="text-sm font-medium text-muted-foreground">
              AI Confidence
            </CardTitle>
          </CardHeader>
          <CardContent>
            <div className="text-3xl font-bold text-blue-600">
              {scan.confidence}%
            </div>
          </CardContent>
        </Card>

        <Card>
          <CardHeader className="pb-2">
            <CardTitle className="text-sm font-medium text-muted-foreground flex items-center gap-2">
              <Calendar className="h-4 w-4" />
              Scan Date
            </CardTitle>
          </CardHeader>
          <CardContent>
            <div className="text-sm font-medium">
              {new Date(scan.timestamp || scan.createdAt).toLocaleDateString()}
            </div>
            <div className="text-xs text-muted-foreground">
              {new Date(scan.timestamp || scan.createdAt).toLocaleTimeString()}
            </div>
          </CardContent>
        </Card>
      </div>

      {/* Facial Metrics */}
      {scan.facialMetrics && (
        <Card>
          <CardHeader>
            <CardTitle className="flex items-center gap-2">
              <Eye className="h-5 w-5" />
              Detailed Facial Metrics
            </CardTitle>
          </CardHeader>
          <CardContent className="space-y-4">
            <div className="grid gap-4 sm:grid-cols-2">
              {Object.entries(scan.facialMetrics).map(([key, value]: [string, any]) => (
                <div key={key} className="space-y-2">
                  <div className="flex justify-between items-center">
                    <span className="text-sm font-medium capitalize">
                      {key.replace(/([A-Z])/g, ' $1').trim()}
                    </span>
                    <span className={`text-sm font-bold ${getScoreColor(value)}`}>
                      {value}%
                    </span>
                  </div>
                  <div className="h-2 bg-gray-200 rounded-full overflow-hidden">
                    <div 
                      className={`h-full ${getProgressColor(value)} transition-all duration-500`}
                      style={{ width: `${value}%` }}
                    />
                  </div>
                </div>
              ))}
            </div>
          </CardContent>
        </Card>
      )}

      {/* Analysis Details */}
      <div className="grid gap-6 md:grid-cols-2">
        <Card>
          <CardHeader>
            <CardTitle>Detected Factors</CardTitle>
          </CardHeader>
          <CardContent>
            {scan.factors && scan.factors.length > 0 ? (
              <ul className="space-y-2">
                {scan.factors.map((factor: string, i: number) => (
                  <li key={i} className="flex items-start gap-2 text-sm">
                    <Activity className="h-4 w-4 text-orange-500 mt-0.5 flex-shrink-0" />
                    <span>{factor}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-muted-foreground">No factors detected</p>
            )}
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>Recommendations</CardTitle>
          </CardHeader>
          <CardContent>
            {scan.recommendations && scan.recommendations.length > 0 ? (
              <ul className="space-y-2">
                {scan.recommendations.map((rec: string, i: number) => (
                  <li key={i} className="flex items-start gap-2 text-sm">
                    <div className="w-6 h-6 rounded-full bg-blue-100 flex items-center justify-center flex-shrink-0">
                      <span className="text-xs font-bold text-blue-600">{i + 1}</span>
                    </div>
                    <span>{rec}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-muted-foreground">No recommendations</p>
            )}
          </CardContent>
        </Card>
      </div>

      {/* Technical Details */}
      <Card>
        <CardHeader>
          <CardTitle>Technical Details</CardTitle>
        </CardHeader>
        <CardContent className="space-y-2 text-sm">
          <div className="flex justify-between">
            <span className="text-muted-foreground">Report ID:</span>
            <span className="font-mono">{scan._id}</span>
          </div>
          {scan.rawAsymmetryScore !== undefined && (
            <div className="flex justify-between">
              <span className="text-muted-foreground">Raw Asymmetry Score:</span>
              <span className="font-mono">{scan.rawAsymmetryScore.toFixed(6)}</span>
            </div>
          )}
          <div className="flex justify-between">
            <span className="text-muted-foreground">Analysis Timestamp:</span>
            <span>{new Date(scan.timestamp || scan.createdAt).toISOString()}</span>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
