"use client";

import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import dynamic from "next/dynamic";
import { useAuth } from "@/components/auth/AuthProvider";
import { RequireAuth } from "@/components/auth/RequireAuth";

const Sparkline = dynamic(
  () => import("@/components/shared/Sparkline").then((mod) => mod.Sparkline),
  {
    ssr: false,
    loading: () => (
      <div className="h-[50px] w-full bg-muted/20 animate-pulse rounded" />
    ),
  }
);
const StrokeSymptomChecker = dynamic(
  () => import("@/components/health/StrokeSymptomChecker").then((mod) => mod.StrokeSymptomChecker),
  { ssr: false }
);
const EmergencyContacts = dynamic(
  () => import("@/components/health/EmergencyContacts").then((mod) => mod.EmergencyContacts),
  { ssr: false }
);
const HealthTips = dynamic(
  () => import("@/components/health/HealthTips").then((mod) => mod.HealthTips),
  { ssr: false }
);
import { RiskBadge } from "@/components/shared/RiskBadge";
import { Brain, Activity, History, ArrowRight, TrendingUp, Eye, AlertCircle, Heart } from "lucide-react";
import Link from "next/link";
import { motion } from "framer-motion";
import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";

interface DashboardStats {
  totalScans: number;
  avgRiskScore: number;
  latestScan: any;
  distribution: {
    low: number;
    medium: number;
    high: number;
  };
  trendData: Array<{ date: string; value: number; index: number }>;
  recentScans: any[];
}

export default function DashboardPage() {
  const { user, loading, signOut } = useAuth() as any;
  const router = useRouter();
  const [stats, setStats] = useState<DashboardStats | null>(null);
  const [loadingStats, setLoadingStats] = useState(true);

  useEffect(() => {
    const fetchStats = async () => {
      try {
        const response = await fetch('/api/stats');
        const data = await response.json();
        setStats(data);
      } catch (error) {
        console.error('Error fetching stats:', error);
      } finally {
        setLoadingStats(false);
      }
    };

    fetchStats();
  }, []);

  if (loading) return <div className="p-8">Loading dashboard...</div>;

  const getRiskLevelColor = (level: string) => {
    switch(level) {
      case 'LOW': return 'text-green-600';
      case 'MEDIUM': return 'text-yellow-600';
      case 'HIGH': return 'text-red-600';
      default: return 'text-gray-600';
    }
  };

  const downloadScanReport = (scan: any) => {
    const reportContent = `
FACIAL ASYMMETRY ANALYSIS REPORT
================================

Date: ${new Date(scan.timestamp || scan.createdAt).toLocaleString()}
Report ID: ${scan._id}

OVERALL ASSESSMENT
------------------
Risk Score: ${scan.riskScore}%
Risk Level: ${scan.riskLevel}
AI Confidence: ${scan.confidence}%

FACIAL METRICS BREAKDOWN
-------------------------
${scan.facialMetrics ? Object.entries(scan.facialMetrics).map(([key, value]) => `${key}: ${value}%`).join('\n') : 'No detailed metrics available'}

DETECTED FACTORS
----------------
${scan.factors?.map((f: string) => `- ${f}`).join('\n') || 'None'}

RECOMMENDATIONS
---------------
${scan.recommendations?.map((r: string, i: number) => `${i + 1}. ${r}`).join('\n') || 'None'}

Generated by Facial Asymmetry Detection System
Report Date: ${new Date().toLocaleString()}
    `;

    const blob = new Blob([reportContent], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `scan-report-${scan._id}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <RequireAuth>
      <div className="container py-8 space-y-8 max-w-7xl">
        <div className="flex items-center justify-between">
          <div>
            <h1 className="text-4xl font-bold tracking-tight">
              Facial Analysis Dashboard
            </h1>
            <p className="text-muted-foreground mt-2">
              Monitor your facial asymmetry and stroke risk assessment history
            </p>
          </div>
          <div className="flex items-center gap-2">
            <Button variant="outline" onClick={() => signOut()}>
              Sign out
            </Button>
          </div>
        </div>

        {/* Main Stats Cards */}
        <div className="grid gap-4 md:grid-cols-2 lg:grid-cols-4">
          <Card className="border-blue-200">
            <CardHeader className="flex flex-row items-center justify-between space-y-0 pb-2">
              <CardTitle className="text-sm font-medium">
                Total Scans
              </CardTitle>
              <Brain className="h-4 w-4 text-blue-600" />
            </CardHeader>
            <CardContent>
              <div className="text-3xl font-bold text-blue-600">
                {loadingStats ? '...' : stats?.totalScans || 0}
              </div>
              <p className="text-xs text-muted-foreground mt-1">
                Facial analyses completed
              </p>
            </CardContent>
          </Card>

          <Card className="border-purple-200">
            <CardHeader className="flex flex-row items-center justify-between space-y-0 pb-2">
              <CardTitle className="text-sm font-medium">
                Average Risk
              </CardTitle>
              <Activity className="h-4 w-4 text-purple-600" />
            </CardHeader>
            <CardContent>
              <div className="text-3xl font-bold text-purple-600">
                {loadingStats ? '...' : `${stats?.avgRiskScore || 0}%`}
              </div>
              <p className="text-xs text-muted-foreground mt-1">
                Average asymmetry score
              </p>
            </CardContent>
          </Card>

          <Card className="border-green-200">
            <CardHeader className="flex flex-row items-center justify-between space-y-0 pb-2">
              <CardTitle className="text-sm font-medium">
                Latest Scan
              </CardTitle>
              <History className="h-4 w-4 text-green-600" />
            </CardHeader>
            <CardContent>
              {loadingStats ? (
                <div className="text-3xl font-bold">...</div>
              ) : stats?.latestScan ? (
                <>
                  <div className={`text-3xl font-bold ${getRiskLevelColor(stats.latestScan.riskLevel)}`}>
                    {stats.latestScan.riskScore}%
                  </div>
                  <p className="text-xs text-muted-foreground mt-1">
                    {new Date(stats.latestScan.timestamp).toLocaleDateString()}
                  </p>
                </>
              ) : (
                <div className="text-sm text-muted-foreground">No scans yet</div>
              )}
            </CardContent>
          </Card>

          <Card className="border-orange-200">
            <CardHeader className="flex flex-row items-center justify-between space-y-0 pb-2">
              <CardTitle className="text-sm font-medium">
                Risk Distribution
              </CardTitle>
              <TrendingUp className="h-4 w-4 text-orange-600" />
            </CardHeader>
            <CardContent>
              {loadingStats ? (
                <div className="text-3xl font-bold">...</div>
              ) : (
                <div className="space-y-1">
                  <div className="flex items-center justify-between text-sm">
                    <span className="text-green-600">Low: {stats?.distribution.low || 0}</span>
                    <span className="text-yellow-600">Med: {stats?.distribution.medium || 0}</span>
                    <span className="text-red-600">High: {stats?.distribution.high || 0}</span>
                  </div>
                </div>
              )}
            </CardContent>
          </Card>
        </div>

        {/* Risk Trend Chart */}
        {stats?.trendData && stats.trendData.length > 0 && (
          <Card className="border-blue-200">
            <CardHeader>
              <CardTitle className="flex items-center gap-2">
                <TrendingUp className="h-5 w-5 text-blue-600" />
                Asymmetry Risk Trend
              </CardTitle>
            </CardHeader>
            <CardContent>
              <Sparkline data={stats.trendData} />
              <p className="text-sm text-muted-foreground mt-2">
                Showing last {stats.trendData.length} scans
              </p>
            </CardContent>
          </Card>
        )}

        {/* Start Scan CTA */}
        <motion.div whileHover={{ scale: 1.01 }} whileTap={{ scale: 0.99 }}>
          <Link href="/scan">
            <Card className="bg-gradient-to-r from-blue-600 to-purple-600 text-white border-none overflow-hidden relative">
              <div className="absolute right-0 top-0 h-full w-1/2 bg-white/10 skew-x-12 transform translate-x-12" />
              <CardContent className="flex items-center justify-between p-8 relative z-10">
                <div className="space-y-2">
                  <h2 className="text-3xl font-bold flex items-center gap-2">
                    <Eye className="h-8 w-8" />
                    Start Facial Analysis
                  </h2>
                  <p className="text-blue-100 max-w-md">
                    Perform AI-powered facial asymmetry detection to assess potential stroke risk indicators
                  </p>
                </div>
                <Button size="lg" variant="secondary" className="gap-2 text-lg px-6">
                  Scan Now <ArrowRight className="h-5 w-5" />
                </Button>
              </CardContent>
            </Card>
          </Link>
        </motion.div>

        {/* Main Content Grid */}
        <div className="grid gap-6 lg:grid-cols-3">
          {/* Left Column - Recent Scans (spans 2 columns) */}
          <Card className="lg:col-span-2">
            <CardHeader>
              <CardTitle className="flex items-center gap-2">
                <History className="h-5 w-5" />
                Recent Scan History
              </CardTitle>
            </CardHeader>
            <CardContent>
              {loadingStats ? (
                <div className="space-y-4">
                  {[1,2,3].map(i => (
                    <div key={i} className="h-16 bg-muted/20 animate-pulse rounded" />
                  ))}
                </div>
              ) : stats?.recentScans && stats.recentScans.length > 0 ? (
                <div className="space-y-4">
                  {stats.recentScans.map((scan: any, i: number) => (
                    <div
                      key={i}
                      className="group relative"
                    >
                      <Link href={`/scans/${scan._id}`}>
                        <div className="flex items-center justify-between p-3 border rounded-lg hover:bg-muted/50 hover:border-blue-300 transition-all cursor-pointer">
                          <div className="space-y-1">
                            <div className="flex items-center gap-2">
                              <RiskBadge level={scan.riskLevel} />
                              <span className="font-medium">{scan.riskScore}%</span>
                            </div>
                            <p className="text-xs text-muted-foreground">
                              {new Date(scan.timestamp || scan.createdAt).toLocaleString()}
                            </p>
                          </div>
                          <div className="flex items-center gap-2">
                            <div className="text-right">
                              <p className="text-xs text-muted-foreground">
                                Confidence: {scan.confidence}%
                              </p>
                            </div>
                            <Button
                              variant="ghost"
                              size="sm"
                              className="opacity-0 group-hover:opacity-100 transition-opacity"
                              onClick={(e) => {
                                e.preventDefault();
                                downloadScanReport(scan);
                              }}
                            >
                              <ArrowRight className="h-4 w-4" />
                            </Button>
                          </div>
                        </div>
                      </Link>
                    </div>
                  ))}
                  <Link href="/history">
                    <Button variant="outline" className="w-full mt-2">
                      View All History
                    </Button>
                  </Link>
                </div>
              ) : (
                <div className="text-center py-8 text-muted-foreground">
                  <AlertCircle className="h-12 w-12 mx-auto mb-2 opacity-50" />
                  <p>No scans yet. Start your first facial analysis!</p>
                  <Link href="/scan">
                    <Button className="mt-4">Perform First Scan</Button>
                  </Link>
                </div>
              )}
            </CardContent>
          </Card>

          {/* Right Sidebar - Emergency Contacts */}
          <div className="space-y-6">
            <EmergencyContacts />
          </div>
        </div>

        {/* Secondary Content Grid */}
        <div className="grid gap-6 lg:grid-cols-2">
          {/* Health Tips - Compact Version */}
          <HealthTips />

          {/* Symptom Checker */}
          <StrokeSymptomChecker />
        </div>

        {/* Understanding Results */}
        <Card>
            <CardHeader>
              <CardTitle>Understanding Your Results</CardTitle>
            </CardHeader>
            <CardContent className="space-y-3">
              <div className="p-3 bg-green-50 rounded-lg border border-green-200">
                <h4 className="font-semibold text-green-800 mb-1">Low Risk (0-30%)</h4>
                <p className="text-sm text-green-700">
                  Minimal facial asymmetry detected. Continue regular monitoring.
                </p>
              </div>
              <div className="p-3 bg-yellow-50 rounded-lg border border-yellow-200">
                <h4 className="font-semibold text-yellow-800 mb-1">Medium Risk (31-70%)</h4>
                <p className="text-sm text-yellow-700">
                  Noticeable asymmetry. Consider consulting a healthcare professional.
                </p>
              </div>
              <div className="p-3 bg-red-50 rounded-lg border border-red-200">
                <h4 className="font-semibold text-red-800 mb-1">High Risk (71-100%)</h4>
                <p className="text-sm text-red-700">
                  Significant asymmetry detected. Seek immediate medical attention.
                </p>
              </div>
              <div className="pt-2 border-t">
                <p className="text-xs text-muted-foreground">
                  <strong>Note:</strong> This tool uses AI to detect facial asymmetry patterns. 
                  Results should be discussed with healthcare professionals.
                </p>
              </div>
            </CardContent>
          </Card>
      </div>
    </RequireAuth>
  );
}